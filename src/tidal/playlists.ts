import { randomUUID } from "node:crypto";
import { request } from "./client.js";

// The create-playlist payload only offers PUBLIC or UNLISTED (PRIVATE shows up
// as a possible state in responses, but isn't a settable value here), so
// UNLISTED is the closest thing to "private" generated playlists can get.
const ACCESS_TYPE = "UNLISTED";
const MAX_ITEMS_PER_REQUEST = 50;
const MARKER = "Generated by needledrop.";

export function defaultPlaylistName(prompt: string): string {
	const trimmed = prompt.trim();
	return trimmed.length > 250 ? trimmed.slice(0, 247) + "..." : trimmed;
};

export function buildPlaylistDescription(prompt: string): string {
	const text = `${MARKER} Prompt: "${prompt}"`;
	return text.length > 500 ? text.slice(0, 497) + "..." : text;
};

export async function createPlaylist(name: string, description: string): Promise<string> {

	const res = await request<{ data: { id: string } }>("/playlists", {
		method: "POST",
		idempotencyKey: randomUUID(),
		body: {
			data: {
				type: "playlists",
				attributes: { name, description, accessType: ACCESS_TYPE }
			}
		}
	});

	return res.data.id;

};

function chunk<T>(items: T[], size: number): T[][] {
	const out: T[][] = [];
	for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
	return out;
};

export async function addItems(playlistId: string, trackIds: string[]): Promise<void> {

	for (const batch of chunk(trackIds, MAX_ITEMS_PER_REQUEST)) {

		await request(`/playlists/${playlistId}/relationships/items`, {
			method: "POST",
			idempotencyKey: randomUUID(),
			body: { data: batch.map((id) => ({ id, type: "tracks" })) }
		});

	};

};
